package httpapi

import (
	"bytes"
	"html/template"
	"net/http"
	"strconv"
)

// The server-rendered login form (arch §8.2, impl-plan §3 WP-12 acceptance 6).
//
// # Why this file exists
//
// The auth gate is all-or-nothing: "with it enabled, static assets are
// protected too, so an unauthenticated visitor cannot even enumerate the SPA's
// routes" (arch §8.2, decision D-23, WP-12 acceptance 6's "including static
// assets"). That is the requirement, and middleware.go implements it literally.
//
// Taken alone it is also unsatisfiable, because arch §7.12's other sentence —
// "the SPA calls /api/auth/status first and renders a login screen" — puts the
// login screen inside the very bundle the gate refuses to serve
// (`web/src/features/auth/LoginScreen.tsx`). The two sentences can only both
// hold if the one document an unauthenticated visitor may have is generated by
// the server. That is this page: it serves no asset, embeds no build hash and
// names no client-side route, so §8.2's guarantee is intact, and it is enough
// to log in with, so §7.12's flow is reachable. Once the cookie exists the SPA
// loads normally and its own LoginScreen handles session expiry from then on.
//
// # Why it has no JavaScript
//
// arch §8.4's CSP is `default-src 'self'` with no `script-src`, so an inline
// `<script>` is refused by the product's own policy and an external one would
// be an asset the gate must not serve. A plain HTML form is therefore the only
// login mechanism that works here — which is why `POST /api/auth/login` accepts
// `application/x-www-form-urlencoded` in addition to the JSON body of §7.12
// (authhandlers.go). `style-src` does allow `'unsafe-inline'`, so the styling
// below is legal as written.
//
// # Why it is a 401 rather than a redirect
//
// The status has to stay 401 so that a client which is not a browser still sees
// the correct code, and so that the URL the visitor typed is still in the
// address bar after logging in.

// loginPageData is the template's input. Deliberately tiny: a login page that
// reflected anything from the request would be a place to inject.
type loginPageData struct {
	// Action is `{base_path}/api/auth/login`, absolute so the form works from
	// any client-side route depth (NFR-SEC-003).
	Action string
	// Message is a fixed string chosen by loginMessage — never the raw error,
	// never anything the client supplied.
	Message string
}

