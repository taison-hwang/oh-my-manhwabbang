// writeLoginPage renders the form.
//
// `Cache-Control: no-store` matters: a proxy or a browser that cached this
// document would keep showing a login form to a session that already exists.
func (s *Server) writeLoginPage(w http.ResponseWriter, r *http.Request, status int, message string) {
	var buf bytes.Buffer
	if err := loginPageTemplate.Execute(&buf, loginPageData{
		Action:  s.base + "/api/auth/login",
		Message: message,
	}); err != nil {
		// The template is a compile-time constant with two string fields, so
		// this cannot happen; if it somehow does, the envelope is still correct.
		writeError(w, r, s.log, internalErr(err))
		return
	}

	h := w.Header()
	h.Set("Content-Type", "text/html; charset=utf-8")
	h.Set("Cache-Control", "no-store")
	h.Set("Content-Length", strconv.Itoa(buf.Len()))
	w.WriteHeader(status)
	if r.Method == http.MethodHead {
		return
	}
	_, _ = w.Write(buf.Bytes())
}

// loginMessage maps a failed login onto the one sentence the form shows.
//
// It is keyed on the status rather than on the error so that the wrong-password
// case cannot accidentally start distinguishing "no password sent" from
// "incorrect password" — arch §8.2 requires those to be indistinguishable.
func loginMessage(status int) string {
	switch status {
	case http.StatusUnauthorized:
		return "비밀번호가 올바르지 않습니다."
	case http.StatusTooManyRequests:
		return "로그인 시도가 너무 많습니다. 잠시 후 다시 시도하세요."
	default:
		return "로그인하지 못했습니다."
	}
}
